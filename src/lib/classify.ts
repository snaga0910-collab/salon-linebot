// お客様のメッセージを、どの種類の問い合わせかに振り分ける。
//
// AIには読ませない。間違った料金を案内しないことが最優先のため（要件定義書 N-01）。
// 言葉が入っているかどうかだけで判断し、迷ったら "other"（＝オーナーへ転送）に倒す。
//
// 分からないものを人に回すので、取りこぼしても事故にはならない。
// ただし拾えるものは拾いたいので、表記のゆれは先にならしてから比べる。

export type Category =
  | "complaint"    // クレーム・お悩み相談　→ 内容に触れず転送
  | "change"       // 予約の変更・キャンセル　→ 【至急】で転送
  | "availability" // 空き状況　　　　　　　→ 一次受けして転送
  | "price"        // 料金　　　　　　　　　→ 自動回答
  | "duration"     // 所要時間　　　　　　　→ 自動回答
  | "hours"        // 営業時間　　　　　　　→ 自動回答
  | "menu"         // メニュー一覧　　　　　→ 自動回答
  | "other";       // それ以外　　　　　　　→ 転送

/** オーナーへ転送し、未対応として記録する種類 */
export const FORWARD_CATEGORIES: Category[] = [
  "complaint",
  "change",
  "availability",
  "other",
];

/**
 * 表記のゆれをならす。
 *
 *   ・全角の英数字や記号を半角に（ＣＵＴ → cut）
 *   ・半角カタカナを全角に（ｶﾗｰ → カラー）
 *   ・カタカナをひらがなに（カラー → からー）
 *   ・長音とハイフンの違いを吸収（カラ- カラ— → からー）
 *   ・空白を落とす
 *
 * 入力文と、照合する言葉の両方に同じ処理をかけるので、
 * 下の RULES には読みやすい書き方（漢字・カタカナ）のまま書いてよい。
 */
export function normalize(s: string): string {
  return s
    .normalize("NFKC")
    .replace(/[ー－‐−–—~〜]/g, "ー")
    .replace(/[ァ-ヶ]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0x60))
    .replace(/\s+/g, "")
    .toLowerCase();
}

/** 上から順に判定する。並び順そのものが仕様。 */
// ひらがなで打つお客様もいるため、漢字の言葉には読みも並べておく。
